//! The general pasteboard for the capture (DESIGN J.3): the change count as
//! the "something was copied" signal, a snapshot of everything on it
//! (items × types × bytes) and the restore of that snapshot.

use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardTypeString, NSPasteboardWriting};
use objc2_foundation::{NSArray, NSData, NSString};

/// Above this total the snapshot keeps only text and images.
pub const SNAPSHOT_LIMIT_BYTES: usize = 64 * 1024 * 1024;

/// Types kept when the pasteboard is too big, in order of importance.
const PRIORITY_TYPES: [&str; 4] = [
    "public.utf8-plain-text",
    "public.rtf",
    "public.png",
    "public.tiff",
];

/// The convention of clipboard managers (nspasteboard.org): "do not record".
const MARKER_TYPES: [&str; 2] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

const PLAIN_TEXT_TYPE: &str = "public.utf8-plain-text";

/// One pasteboard item: its types with their bytes, in the owner's order.
pub type Item = Vec<(String, Vec<u8>)>;

#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Snapshot {
    pub items: Vec<Item>,
}

/// `changeCount` as the sequence number of the capture (only compared for
/// equality, so the wrap-around of `as u32` is harmless).
pub fn change_count() -> u32 {
    NSPasteboard::generalPasteboard().changeCount() as u32
}

fn total_bytes(items: &[Item]) -> usize {
    items.iter().flatten().map(|(_, data)| data.len()).sum()
}

/// Keeps a snapshot within `limit`: whole if it fits, otherwise only the
/// priority types (text, RTF, PNG, TIFF), otherwise only the plain text.
/// Items left without any type are dropped. Pure, so it is tested.
pub fn limit_snapshot(items: Vec<Item>, limit: usize) -> Vec<Item> {
    if total_bytes(&items) <= limit {
        return items;
    }
    let keep = |items: Vec<Item>, wanted: &[&str]| -> Vec<Item> {
        items
            .into_iter()
            .map(|item| {
                item.into_iter()
                    .filter(|(ty, _)| wanted.contains(&ty.as_str()))
                    .collect::<Item>()
            })
            .filter(|item| !item.is_empty())
            .collect()
    };
    let kept = keep(items, &PRIORITY_TYPES);
    if total_bytes(&kept) <= limit {
        kept
    } else {
        keep(kept, &PRIORITY_TYPES[..1])
    }
}

/// Reads everything on the pasteboard. Promised (lazy) data is rendered by
/// the owner while it is read, as with delayed rendering on Windows.
pub fn take_snapshot() -> Result<Snapshot, String> {
    let pasteboard = NSPasteboard::generalPasteboard();
    let mut items = Vec::new();
    if let Some(array) = pasteboard.pasteboardItems() {
        for item in array.iter() {
            let mut entries = Item::new();
            for ty in item.types().iter() {
                if let Some(data) = item.dataForType(&ty) {
                    entries.push((ty.to_string(), data.to_vec()));
                }
            }
            if !entries.is_empty() {
                items.push(entries);
            }
        }
    }
    Ok(Snapshot {
        items: limit_snapshot(items, SNAPSHOT_LIMIT_BYTES),
    })
}

/// Writes `items` as one `NSPasteboardItem` each (the first one also carries
/// the "transient / auto-generated" markers when `markers` is set).
fn write_items(items: &[Item], markers: bool) -> Result<(), String> {
    let pasteboard = NSPasteboard::generalPasteboard();
    pasteboard.clearContents();
    if items.is_empty() {
        return Ok(());
    }
    let mut objects: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = Vec::new();
    for (index, item) in items.iter().enumerate() {
        let target = NSPasteboardItem::new();
        for (ty, bytes) in item {
            target.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(ty));
        }
        if markers && index == 0 {
            for marker in MARKER_TYPES {
                target.setData_forType(&NSData::with_bytes(&[]), &NSString::from_str(marker));
            }
        }
        objects.push(ProtocolObject::from_retained(target));
    }
    if pasteboard.writeObjects(&NSArray::from_retained_slice(&objects)) {
        Ok(())
    } else {
        Err("The pasteboard did not accept the items".into())
    }
}

/// Puts the snapshot back unless the change count is no longer `expected`
/// (the user copied something meanwhile). `Ok(false)` = skipped. The window
/// between the check and `clearContents` is microseconds (DESIGN J.3).
pub fn restore_snapshot(snapshot: &Snapshot, expected: u32) -> Result<bool, String> {
    if change_count() != expected {
        return Ok(false);
    }
    write_items(&snapshot.items, true)?;
    Ok(true)
}

/// The plain text on the pasteboard now.
pub fn read_text() -> Option<String> {
    let pasteboard = NSPasteboard::generalPasteboard();
    // SAFETY: NSPasteboardTypeString is a read-only framework constant.
    let text = pasteboard.stringForType(unsafe { NSPasteboardTypeString })?;
    Some(text.to_string())
}

/// Replaces the pasteboard with `text` (marked so that clipboard managers skip
/// it) and returns the change count of that write.
pub fn put_text(text: &str) -> Result<u32, String> {
    let item: Item = vec![(PLAIN_TEXT_TYPE.to_string(), text.as_bytes().to_vec())];
    write_items(&[item], true)?;
    Ok(change_count())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(ty: &str, len: usize) -> (String, Vec<u8>) {
        (ty.to_string(), vec![0; len])
    }

    #[test]
    fn a_small_snapshot_is_kept_whole() {
        let items = vec![vec![
            entry("public.utf8-plain-text", 5),
            entry("x.custom", 7),
        ]];
        assert_eq!(limit_snapshot(items.clone(), 100), items);
    }

    #[test]
    fn a_big_snapshot_keeps_text_and_images_only() {
        let items = vec![
            vec![
                entry("public.utf8-plain-text", 10),
                entry("public.png", 20),
                entry("x.huge", 500),
            ],
            vec![entry("x.other", 5)],
        ];
        let kept = limit_snapshot(items, 100);
        assert_eq!(
            kept,
            vec![vec![
                entry("public.utf8-plain-text", 10),
                entry("public.png", 20)
            ]]
        );
    }

    #[test]
    fn a_snapshot_still_too_big_keeps_the_plain_text() {
        let items = vec![vec![
            entry("public.tiff", 500),
            entry("public.utf8-plain-text", 10),
        ]];
        assert_eq!(
            limit_snapshot(items, 100),
            vec![vec![entry("public.utf8-plain-text", 10)]]
        );
    }

    #[test]
    fn the_plain_text_is_never_dropped() {
        let items = vec![vec![entry("public.utf8-plain-text", 500)]];
        // The plain text is kept even if it alone is over the limit.
        assert_eq!(limit_snapshot(items.clone(), 100), items);
    }

    /// Runs `f` with the user's own pasteboard put back afterwards.
    fn keeping_the_users_pasteboard(f: impl FnOnce()) {
        let mine = take_snapshot().unwrap();
        f();
        write_items(&mine.items, false).unwrap();
    }

    fn bytes_of(snapshot: &Snapshot, ty: &str) -> Option<Vec<u8>> {
        snapshot
            .items
            .iter()
            .flatten()
            .find(|(t, _)| t == ty)
            .map(|(_, data)| data.clone())
    }

    #[test]
    #[ignore = "uses the real pasteboard"]
    fn text_rtf_and_png_come_back_byte_for_byte() {
        keeping_the_users_pasteboard(|| {
            let png: Vec<u8> = (0..=255u8).cycle().take(5000).collect();
            let rtf = br"{\rtf1\ansi Hello \b world\b0}".to_vec();
            let item: Item = vec![
                (
                    "public.utf8-plain-text".into(),
                    "Hello world".as_bytes().to_vec(),
                ),
                ("public.rtf".into(), rtf.clone()),
                ("public.png".into(), png.clone()),
            ];
            write_items(&[item], false).unwrap();
            let before = take_snapshot().unwrap();

            put_text("something else").unwrap();
            assert_eq!(read_text().as_deref(), Some("something else"));
            assert!(restore_snapshot(&before, change_count()).unwrap());

            let after = take_snapshot().unwrap();
            assert_eq!(read_text().as_deref(), Some("Hello world"));
            assert_eq!(bytes_of(&after, "public.rtf"), Some(rtf));
            assert_eq!(bytes_of(&after, "public.png"), Some(png));
            // Restored with the "do not record" markers.
            assert!(bytes_of(&after, MARKER_TYPES[0]).is_some());
        });
    }

    #[test]
    #[ignore = "uses the real pasteboard"]
    fn a_newer_copy_of_the_user_is_left_alone() {
        keeping_the_users_pasteboard(|| {
            put_text("before").unwrap();
            let before = take_snapshot().unwrap();
            let expected = change_count();
            put_text("copied by the user meanwhile").unwrap();
            assert!(!restore_snapshot(&before, expected).unwrap());
            assert_eq!(read_text().as_deref(), Some("copied by the user meanwhile"));
        });
    }

    #[test]
    #[ignore = "uses the real pasteboard"]
    fn an_empty_pasteboard_is_restored_empty() {
        keeping_the_users_pasteboard(|| {
            NSPasteboard::generalPasteboard().clearContents();
            let empty = take_snapshot().unwrap();
            assert!(empty.items.is_empty());
            put_text("temporary").unwrap();
            assert!(restore_snapshot(&empty, change_count()).unwrap());
            assert_eq!(read_text(), None);
        });
    }
}
